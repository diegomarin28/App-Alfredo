test('crear con 1 mes antes guarda 30 días', async ({ page }) => {
  await resetear(page, { hoy: '2026-03-01' })
  await entrarComo(page, 'owner')
  await page.goto('/recordatorios')
  await page.getByRole('button', { name: 'Agregar recordatorio' }).click()
  const hoja = page.getByRole('dialog')
  await hoja.getByLabel('Título').fill('Renovar seguro')
  await hoja.getByLabel('Día', { exact: true }).selectOption('15')
  await hoja.getByLabel('Mes').selectOption('9')
  await hoja.getByRole('button', { name: '1 mes' }).click()
  await hoja.getByRole('button', { name: 'Guardar' }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  const fila = page.getByRole('region', { name: 'Todos los años' }).getByRole('listitem').filter({ hasText: 'Renovar seguro' })
  await expect(fila).toContainText('15 sep')
  await expect(fila).toContainText('1 mes antes')
})

