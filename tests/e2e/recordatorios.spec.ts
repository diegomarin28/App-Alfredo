import { test, expect } from '@playwright/test'
import { entrarComo, resetear } from './helpers'

const HOY = '2026-10-26'

test('activos: Navidad con Posponer y Resuelto; Posponer lo oculta', async ({ page }) => {
  await resetear(page, { hoy: HOY })
  await entrarComo(page, 'owner')
  await page.goto('/recordatorios')
  const activos = page.getByRole('region', { name: 'Para gestionar ahora' })
  const navidad = activos.getByRole('article', { name: 'Gestionar Navidad' })
  await expect(navidad).toContainText('25 de diciembre')
  await expect(navidad).toContainText('faltan 60 días')
  await navidad.getByRole('button', { name: 'Posponer' }).click()
  // hoja chica, siempre de menor a mayor (ronda 5): la por defecto (15 días) marcada en su lugar
  const hoja = page.getByRole('dialog', { name: 'Posponer Gestionar Navidad' })
  const opciones = hoja.getByRole('radio')
  await expect(opciones).toHaveCount(6)
  expect(await hoja.locator('label').allTextContents()).toEqual(['1 día', '3 días', '1 semana', '15 días', '1 mes', 'Elegir fecha'])
  await expect(hoja.getByRole('radio', { name: '15 días' })).toBeChecked()
  await hoja.getByRole('button', { name: 'Posponer' }).click()
  await expect(page.getByText('Te lo recuerdo de nuevo en 15 días.')).toBeVisible()
  await expect(activos.getByRole('article', { name: 'Gestionar Navidad' })).toHaveCount(0)
})

test('Posponer eligiendo cuánto: 3 días, o hasta una fecha', async ({ page }) => {
  await resetear(page, { hoy: HOY })
  await entrarComo(page, 'owner')
  await page.goto('/recordatorios')
  const activos = page.getByRole('region', { name: 'Para gestionar ahora' })
  await activos.getByRole('article', { name: 'Gestionar Navidad' }).getByRole('button', { name: 'Posponer' }).click()
  let hoja = page.getByRole('dialog', { name: 'Posponer Gestionar Navidad' })
  await hoja.getByRole('radio', { name: '3 días' }).check()
  await hoja.getByRole('button', { name: 'Posponer' }).click()
  await expect(page.getByText('Te lo recuerdo de nuevo en 3 días.')).toBeVisible()
  await expect(activos.getByRole('article', { name: 'Gestionar Navidad' })).toHaveCount(0)
  // que termine la recarga de datos de la pantalla antes de resetear (si llega después, Next recarga la página
  // entera y pisa la navegación de abajo)
  await page.waitForLoadState('networkidle')

  // de nuevo desde cero: ahora hasta una fecha elegida
  await resetear(page, { hoy: HOY })
  await page.goto('/recordatorios')
  await activos.getByRole('article', { name: 'Gestionar Navidad' }).getByRole('button', { name: 'Posponer' }).click()
  hoja = page.getByRole('dialog', { name: 'Posponer Gestionar Navidad' })
  await hoja.getByRole('radio', { name: 'Elegir fecha' }).check()
  await expect(hoja.getByRole('button', { name: 'Posponer' })).toBeDisabled()
  await hoja.getByLabel('Hasta').fill('2026-12-01')
  await hoja.getByRole('button', { name: 'Posponer' }).click()
  await expect(page.getByText('Te lo recuerdo de nuevo el 1 de diciembre.')).toBeVisible()
})

test('API posponer: por días o fecha; una fecha que no es futura da 400', async ({ page }) => {
  await resetear(page, { hoy: HOY, datos: { recordatorios: [{ id: 'r1', titulo: 'Pagar patente', dia: '11-10', avisarDiasAntes: 30 }] } })
  await entrarComo(page, 'owner')
  const ok = await page.request.post('/api/recordatorios/r1', { data: { accion: 'posponer', dias: 7 } })
  expect((await ok.json()).pospuestoHasta).toBe('2026-11-02')
  const fecha = await page.request.post('/api/recordatorios/r1', { data: { accion: 'posponer', hasta: '2026-11-05' } })
  expect((await fecha.json()).pospuestoHasta).toBe('2026-11-05')
  const mal = await page.request.post('/api/recordatorios/r1', { data: { accion: 'posponer', hasta: HOY } })
  expect(mal.status()).toBe(400)
})

test('ronda 4b: "Se repite" (todos los años por defecto), Día/Mes en "Elegí", y "No se repite" pide el año', async ({ page }) => {
  await resetear(page, { hoy: '2026-03-01' })
  await entrarComo(page, 'owner')
  await page.goto('/recordatorios')
  await page.getByRole('button', { name: 'Agregar recordatorio' }).click()
  const hoja = page.getByRole('dialog')
  await expect(hoja.getByLabel('Se repite')).toHaveValue('anual')
  await expect(hoja.getByLabel('Día', { exact: true })).toHaveValue('')
  await expect(hoja.getByLabel('Posponer, por defecto')).toHaveValue('15')
  await hoja.getByLabel('Título').fill('Renovar pasaporte')
  await hoja.getByLabel('Se repite').selectOption('nunca')
  await hoja.getByLabel('Día', { exact: true }).selectOption('20')
  await hoja.getByLabel('Mes').selectOption('5')
  await hoja.getByRole('button', { name: 'Guardar' }).click()
  await expect(hoja.getByText('Elegí el año.')).toBeVisible()
  await hoja.getByLabel('Año').fill('2027')
  await hoja.getByLabel('Posponer, por defecto').selectOption('7')
  await hoja.getByRole('button', { name: 'Guardar' }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  const fila = page.getByRole('region', { name: 'Todos los recordatorios' }).getByRole('listitem').filter({ hasText: 'Renovar pasaporte' })
  await expect(fila).toContainText('20 may 2027 · una vez')
})

