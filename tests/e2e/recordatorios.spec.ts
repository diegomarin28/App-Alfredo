test('API: validación y familia', async ({ page }) => {
  await resetear(page, { hoy: HOY })
  await entrarComo(page, 'familia')
  const r404 = await page.request.post('/api/recordatorios/no-existe', { data: { accion: 'resolver' } })
  expect(r404.status()).toBe(404)
  const r400 = await page.request.post('/api/recordatorios/no-existe', { data: { accion: 'borrar' } })
  expect(r400.status()).toBe(400)
  await page.goto('/recordatorios')
  await expect(page.getByRole('region', { name: 'Para gestionar ahora' })).toBeVisible()
})

test('editar fecha de uno resuelto lo reactiva; editar sin fecha no inventa 1 de enero', async ({ page }) => {
  await resetear(page, { hoy: HOY })
  await entrarComo(page, 'owner')
  await page.goto('/recordatorios')
  const activos = page.getByRole('region', { name: 'Para gestionar ahora' })
  await activos.getByRole('article', { name: 'Gestionar Navidad' }).getByRole('button', { name: 'Resuelto' }).click()
  await expect(page.getByText('¡Listo!')).toBeVisible()
  const lista = page.getByRole('region', { name: 'Todos los años' })
  await lista.getByRole('listitem').filter({ hasText: 'Gestionar Navidad' }).getByRole('button', { name: 'Editar' }).click()
  await page.getByRole('dialog').getByLabel('Día', { exact: true }).selectOption('20')
  await page.getByRole('dialog').getByRole('button', { name: 'Guardar' }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.reload()
  await expect(activos.getByRole('article', { name: 'Gestionar Navidad' })).toContainText('20 de diciembre')

  const fila = lista.getByRole('listitem').filter({ hasText: 'Sacar pasajes de los chicos' })
  await fila.getByRole('button', { name: 'Editar' }).click()
  const hoja = page.getByRole('dialog')
  await expect(hoja.getByLabel('Día', { exact: true })).toHaveValue('')
  await hoja.getByLabel('Título').fill('Pasajes de los chicos')
  await hoja.getByRole('button', { name: 'Guardar' }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(lista.getByRole('listitem').filter({ hasText: 'Pasajes de los chicos' })).toContainText('fecha a cargar')
})
